#!/bin/sh
set -e

# 1) Migration awal dibuat dari schema.prisma bila folder prisma/migrations masih kosong.
#    Hasilnya tersimpan di ./backend/prisma/migrations (volume) -> commit ke repository.
if [ -z "$(ls -A prisma/migrations 2>/dev/null | grep -v -e migration_lock.toml -e .gitkeep)" ]; then
  echo "[entrypoint] Membuat migration awal dari schema.prisma ..."
  mkdir -p prisma/migrations/00000000000000_init
  F=prisma/migrations/00000000000000_init/migration.sql
  npx prisma migrate diff --from-empty --to-schema prisma/schema.prisma --script > "$F" 2>/dev/null \
    || npx prisma migrate diff --from-empty --to-schema-datamodel prisma/schema.prisma --script > "$F"
  printf '# Please do not edit this file manually\n# It should be added in your version-control system (e.g., Git)\nprovider = "mysql"\n' > prisma/migrations/migration_lock.toml
fi

# 2) Terapkan migration (dicoba ulang sampai MySQL siap).
i=0
until npx prisma migrate deploy; do
  i=$((i+1)); [ "$i" -ge 20 ] && { echo "[entrypoint] Migration gagal."; exit 1; }
  echo "[entrypoint] Menunggu database ($i/20) ..."; sleep 3
done

# 3) Seed data awal (idempotent).
if [ "$SEED_ON_START" != "false" ]; then node prisma/seed.js; fi

exec node src/server.js
